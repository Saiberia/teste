export const DICTS = Object.freeze({ ru, en });
export const LANGS = Object.freeze(Object.keys(DICTS));

/** Server `ui_language` → a supported language (Russian by default). */
export function pickLanguage(value) {
  const v = String(value || "").toLowerCase().slice(0, 2);
  return LANGS.includes(v) ? v : "ru";
}

/** Translation with {placeholders}; falls back to Russian, then to the key. */
export function translate(lang, key, vars) {
  const dict = DICTS[lang] || ru;
  let s = dict[key] ?? ru[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

export function makeT(lang) {
  const l = pickLanguage(lang);
  const t = (key, vars) => translate(l, key, vars);
  t.lang = l;
  return t;
}
